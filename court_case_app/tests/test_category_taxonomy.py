@pytest.mark.parametrize("text,expected", SAMPLES)
def test_get_group_real_samples(text, expected):
    assert get_group(text) == expected


def test_all_groups_have_short_names():
    for name, _patterns in CANON_RULES:
        assert name in SHORT_NAMES, f"Нет короткого имени для {name!r}"


def test_normalize_yo_and_case():
    assert normalize("Споры ЁЖ") == "споры еж"
    assert normalize("  А  Б  ") == "а б"


def test_normalize_punctuation():
    assert normalize("строка, )") == "строка"
    assert normalize("строка ,еще") == "строка,еще"
    assert normalize("строка   с   пробелами") == "строка с пробелами"


def test_normalize_quotes_dashes():
    assert normalize("«тест»") == '"тест"'
    assert normalize("а – б") == "а - б"


def test_get_group_empty_and_none():
    assert get_group("") is None
    assert get_group(None) is None
    assert get_group("   ") is None


def test_get_group_unknown():
    assert get_group("совершенно непонятная строка без ключевых слов") is None


def test_get_short_name():
    assert get_short_name("Споры, связанные с жилищными отношениями") == "Жилищные"
    assert get_short_name(None) == ""
    assert get_short_name("") == ""
    assert get_short_name("Неизвестная группа") == "Неизвестная группа"


def test_split_with_o():
    main, sub, detail = split(
        "Споры, связанные с жилищными отношениями О взыскании платы за жилую площадь")
    assert main == "споры, связанные с жилищными отношениями"
    assert sub.startswith("о взыскании")
    assert detail == ""


def test_split_starts_with_o():
    main, sub, detail = split("о взыскании алиментов на содержание детей")
    assert main == ""
    assert sub == "о взыскании алиментов на содержание детей"


def test_split_with_krome():
    main, sub, detail = split(
        "Иски, связанные с возмещением ущерба иски о возмещении ущерба от дтп (кроме увечий и смерти кормильца)")
    assert "возмещением ущерба" in main
    assert "кроме" in detail


def test_idempotent_get_group():
    text = "Споры, связанные с жилищными отношениями о взыскании платы"
    assert get_group(text) == get_group(text)

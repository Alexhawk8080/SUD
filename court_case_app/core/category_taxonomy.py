# --- Публичный API ----------------------------------------------------------

def get_group(text):
    """Канон-группа по тексту категории. None — не распознано."""
    norm = normalize(text)
    if not norm:
        return None
    for name, patterns in CANON_RULES:
        for p in patterns:
            if p in norm:
                return name
    return None


def get_short_name(group):
    """Короткое имя группы для UI. Пустая строка для None."""
    if not group:
        return ""
    return SHORT_NAMES.get(group, group)


def split(text):
    """(верхний_уровень, подкатегория, третий_уровень).

    Третий уровень — всё после «кроме», «за исключением».
    Пока не используется, но полезно для аналитики.
    """
    norm = normalize(text)
    if not norm:
        return "", "", ""
    m = _SPLIT_RE.search(norm)
    if not m:
        return norm, "", ""
    start = m.start(1)
    main = norm[:start].strip(" ,;:-")
    tail = norm[start:].strip()
    detail = ""
    for sep in ("кроме", "за исключением"):
        pos = tail.find(sep)
        if pos > 0:
            detail = tail[pos:].strip()
            tail = tail[:pos].strip(" ,;:-")
            break
    return main, tail, detail

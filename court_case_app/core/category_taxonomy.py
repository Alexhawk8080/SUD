from __future__ import annotations

import re

# --- Нормализация -----------------------------------------------------------

_PUNCT_TAIL = re.compile(r"[\s,;:\)\]]+$")
_SPACE_BEFORE_PUNCT = re.compile(r"\s+([,;:.\)\]])")
_MULTI_SPACE = re.compile(r"\s+")
_SPLIT_RE = re.compile(r"(?:^|\s)(о|об)\s", re.IGNORECASE)


def normalize(text) -> str:
    """Нормализация: strip, lower, ё→е, кавычки/тире, схлопывание пробелов."""
    if text is None:
        return ""
    s = str(text).strip().lower().replace("ё", "е")
    s = (s.replace("«", '"').replace("»", '"')
           .replace("“", '"').replace("”", '"')
           .replace("–", "-").replace("—", "-"))
    s = _SPACE_BEFORE_PUNCT.sub(r"\1", s)
    s = _PUNCT_TAIL.sub("", s)
    return _MULTI_SPACE.sub(" ", s).strip()



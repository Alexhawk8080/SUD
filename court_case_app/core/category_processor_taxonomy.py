# Гипотеза срока хранения по канон-группе.
# Заполнено ТОЛЬКО там, где есть уверенность в дефолте группы.
# Остальные группы возвращают None — молчание в логе, пока не накопим данные.
RETENTION_BY_GROUP = {
    "Споры, связанные с жилищными отношениями": "3 года Ст. 227",
    "Производство по делам о взыскании обязательных платежей и санкций": "3 года Ст. 221",
    "Отношения, связанные с защитой прав потребителей": "3 года ЭПК Ст. 208",
    "Споры, возникающие из пенсионных правоотношений": "5 лет ЭПК Ст. 203",
}


def taxonomy_prefix(category):
    """Гипотеза prefix по канон-группе. None — нет гипотезы."""
    group = get_group(category)
    if not group:
        return None
    return PREFIX_BY_GROUP.get(group)


def taxonomy_retention(category):
    """Гипотеза срока хранения по канон-группе. None — нет гипотезы."""
    group = get_group(category)
    if not group:
        return None
    return RETENTION_BY_GROUP.get(group)

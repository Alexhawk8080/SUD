# -*- coding: utf-8 -*-
"""
Тесты сроков хранения (Этап 3). Сверка всех категорий с VBA-логикой 1:1.

ВАЖНО: ожидания отражают ФАКТИЧЕСКОЕ поведение VBA-макроса, включая его
особенности. Например, слово «взыскании» в начале категории содержит корень
«взыскани» (тип "collection"), у которого в Select Case VBA нет ветки —
результат всегда «3 года Ст. 227», даже если далее есть «алименты», «налог»
и т.п. Порт воспроизводит это поведение точно.

Запуск: .venv\\Scripts\\python.exe court_case_app\\tests\\test_retention.py
"""

import sys
import os

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from core.retention import get_retention_info

FAILED = 0
PASSED = 0


def check(name: str, category, expected: str):
    global FAILED, PASSED
    actual = get_retention_info(category)
    ok = actual == expected
    if ok:
        PASSED += 1
        print(f"  OK   {name}")
    else:
        FAILED += 1
        print(f"  FAIL {name}\n       ожидалось: {expected!r}\n       получено:  {actual!r}")


def main():
    print("[1] Алименты")
    # Особенность VBA: «взыскании» -> collection -> дефолт 227
    check("О взыскании алиментов (особенность: collection -> 227)",
          "О взыскании алиментов на содержание несовершеннолетних детей",
          "3 года Ст. 227")
    check("Об изменении размера алиментов",
          "Об изменении размера алиментов",
          "1 год ЭК Ст. 139")
    check("Об уплате алиментов другим лицом (ст. 140)",
          "Об уплате алиментов другим лицом",
          "1 год ЭК Ст. 140")
    check("Алименты на содержание детей (без 'о взыскании')",
          "Алименты на содержание несовершеннолетних детей",
          "1 год ЭК Ст. 139")

    print("\n[2] Развод")
    check("О расторжении брака супругов - имеющих детей",
          "О расторжении брака супругов - имеющих детей",
          "3 года ЭК Ст. 137")
    check("О признании брака недействительным",
          "О признании брака недействительным",
          "3 года ЭК Ст. 137")

    print("\n[3] Жилищные")
    # «выселении» и «жилого» не содержат ключей housing -> дефолт
    check("О выселении из жилого помещения (нет ключа -> 227)",
          "О выселении из жилого помещения",
          "3 года Ст. 227")
    check("О взыскании задолженности по коммунальным платежам (collection -> 227)",
          "О взыскании задолженности по коммунальным платежам",
          "3 года Ст. 227")
    check("О признании права на жилищную субсидию",
          "О признании права на жилищную субсидию",
          "3 года Ст. 179")

    print("\n[4] Страховые")
    check("О взыскании страхового возмещения (collection -> 227)",
          "О взыскании страхового возмещения",
          "3 года Ст. 227")
    check("О страховом возмещении",
          "О страховом возмещении",
          "3 года Ст. 201")
    check("О взыскании страховых взносов (collection -> 227)",
          "О взыскании страховых взносов",
          "3 года Ст. 227")

    print("\n[5] Пенсионные")
    check("О восстановлении нарушенных пенсионных прав",
          "О восстановлении нарушенных пенсионных прав",
          "5 лет ЭПК Ст. 203")
    check("О назначении пенсии",
          "О назначении пенсии",
          "5 лет ЭПК Ст. 203")
    check("О перерасчете пенсии",
          "О перерасчете пенсии",
          "5 лет ЭПК Ст. 202")
    check("О взыскании выплат по пенсионному обеспечению (collection -> 227)",
          "О взыскании выплат по пенсионному обеспечению",
          "3 года Ст. 227")
    check("Выплаты по пенсионному обеспечению",
          "Выплаты по пенсионному обеспечению",
          "5 лет ЭПК Ст. 203")

    print("\n[6] Потребители")
    check("О защите прав потребителей - из договоров в сфере услуги торговли",
          "О защите прав потребителей - из договоров в сфере услуги торговли",
          "3 года ЭПК Ст. 208")

    print("\n[7] Налоги")
    check("О взыскании налога (collection -> 227)",
          "О взыскании налога",
          "3 года Ст. 227")
    check("О признании недействительным решения налогового органа",
          "О признании недействительным решения налогового органа",
          "3 года Ст. 221")
    check("Налоговый спор о взыскании недоимки",
          "Налоговый спор о взыскании недоимки",
          "3 года Ст. 221")

    print("\n[8] Займы/долги")
    check("О взыскании долга по договору займа (collection -> 227)",
          "О взыскании долга по договору займа",
          "3 года Ст. 227")
    check("О возврате долга по договору займа",
          "О возврате долга по договору займа",
          "3 года Ст. 222")
    check("О взыскании задолженности по расписке (collection -> 227)",
          "О взыскании задолженности по расписке",
          "3 года Ст. 227")

    print("\n[9] Кредиты")
    check("О взыскании задолженности по кредитному договору (collection -> 227)",
          "О взыскании задолженности по кредитному договору",
          "3 года Ст. 227")
    check("О кредитном договоре",
          "О кредитном договоре",
          "3 года Ст. 223")

    print("\n[10] Прочее и граничные случаи")
    check("Неизвестная категория -> дефолт",
          "О возмещении морального вреда",
          "3 года Ст. 227")
    check("None -> дефолт", None, "3 года Ст. 227")
    check("Пустая строка -> дефолт", "   ", "3 года Ст. 227")

    print(f"\nИТОГО: пройдено {PASSED}, ошибок {FAILED}")
    sys.exit(1 if FAILED else 0)


if __name__ == "__main__":
    main()
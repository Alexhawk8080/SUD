// Heartbeat Web Worker: шлёт /heartbeat каждые 4 секунды.
//
// Зачем Worker, а не setInterval в главном потоке:
//  - Chrome замедляет таймеры свёрнутых/фоновых вкладок (вплоть до 1 раза в минуту),
//    из-за чего heartbeat пропадал и сервер останавливался при открытой вкладке;
//  - Web Workers в фоне НЕ замедляются — heartbeat идёт стабильно;
//  - при закрытии вкладки/окна Worker уничтожается вместе с ней,
//    heartbeat прекращается, и watchdog на сервере останавливает процесс.
// При переходе между страницами приложения старый Worker завершается (pagehide),
// а новая страница сразу создаёт свой — сервер это не замечает.

function beat() {
    try {
        fetch("/heartbeat", { cache: "no-store" }).catch(function () { /* сервер может быть занят */ });
    } catch (e) { /* ignore */ }
}

beat();
setInterval(beat, 4000);